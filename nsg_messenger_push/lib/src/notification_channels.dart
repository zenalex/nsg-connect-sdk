/// **Каналы уведомлений Android** — клиентская половина этапа 3
/// `platform/docs/TASK_TITAN_PRODUCT_PUSH01.md` §4.1.
///
/// **Зачем.** На Android 8+ важность, всплытие поверх экрана и право
/// обойти «Не беспокоить» — свойства КАНАЛА, а не отдельного сообщения.
/// Серверный `priority=high` их не заменяет: он про срочность доставки, а
/// не про то, как уведомление показано. Без выделенного канала тревога
/// охранного приложения приедет в канал по умолчанию с обычной
/// важностью — тихо, без всплытия, в общей пачке.
///
/// **Канал создаёт ПРИЛОЖЕНИЕ, а не сообщение.** Сервер кладёт в нагрузку
/// только идентификатор (`android.notification.channel_id`); сам канал —
/// со всеми своими свойствами — обязан быть заранее заведён на устройстве.
/// Отсюда правило, которому подчинён весь этот файл: **строки обязаны
/// совпадать с серверными ДОСЛОВНО**
/// (`server/nsg_connect/nsg_connect_server/lib/src/push/`
/// `notification_channel.dart`). Firebase на незнакомый идентификатор
/// молча подставляет канал из манифеста: расхождение в один символ
/// превратит тревогу в обычное уведомление, и никакой ошибки не придёт —
/// ни в логе, ни в ответе ручки. Совпадение стережёт
/// `test/notification_channels_test.dart`: он читает серверный файл и
/// падает, если наборы разошлись.
///
/// **Почему каналов ДВА.** Канал — единица пользовательского управления:
/// человек может выключить категорию, не выключая приложение. Сложи мы
/// тревоги и рядовые статусы объектов в один канал — тот, кому надоели
/// статусы, выключил бы вместе с ними и тревоги, о чём узнал бы в худший
/// момент.
///
/// **Оба канала нужны обоим путям доставки.** RuStore (VKPNS) сегодня
/// идентификатор канала не получает — намеренно, поддержку ключа у VKPNS
/// ещё не проверяли против живого API (этап 6 ТЗ). Но каналы на устройстве
/// от этого не зависят: их заводит приложение при старте, а не сообщение.
/// Заведи мы их только на FCM-пути — телефон без сервисов Google остался бы
/// вовсе без категорий в системных настройках.
///
/// ## Что менять уже нельзя, а что можно
///
/// Свойства канала (важность, звук, вибрация, обход «Не беспокоить»)
/// фиксируются при ПЕРВОМ создании: повторный `createNotificationChannel`
/// обновляет только имя, описание и группу. Удалить и создать заново —
/// не лечение: система помнит удалённые каналы и восстанавливает **прежние
/// пользовательские настройки**, а не наши новые. Настоящая смена свойств
/// требует нового идентификатора, а он у нас в закрытом наборе, общем с
/// сервером, — то есть это согласованное изменение обеих половин, а не
/// правка одной строки здесь.
///
/// Имя и описание, наоборот, обновляемы — поэтому повторный вызов
/// [NsgNotificationChannels.ensureCreated] с другими подписями это
/// штатный способ переименовать категории при смене языка приложения.
///
/// ## Чего здесь сознательно нет
///
/// * **Своего звукового файла.** Звук канала — ресурс `res/raw/…` в
///   host-приложении, dart-пакет его не везёт. Указать имя ресурса «на
///   будущее» нельзя: несуществующий ресурс даёт канал с битым URI, то
///   есть **навсегда молчащий**, и починить его нельзя (см. выше про
///   фиксацию свойств). Поэтому берём системный звук уведомлений —
///   отдельный канал и так позволяет человеку назначить тревогам свой.
/// * **Обхода «Не беспокоить»** (`bypassDnd`). Он требует доступа к
///   политике уведомлений (`requestNotificationPolicyAccess`), который
///   выдаёт пользователь на отдельном системном экране. Гарантировать
///   обход мы не можем и обещать Титану не будем — §6.7 ТЗ. Если он
///   понадобится, проверять на устройстве придётся не только выдачу
///   доступа, но и применится ли флаг к УЖЕ созданному каналу.
library;

import 'dart:io' show Platform;

import 'package:flutter/foundation.dart';
import 'package:flutter_local_notifications/flutter_local_notifications.dart';

/// Закрытый набор каналов и их создание на устройстве.
///
/// Зовётся при инициализации SDK из обоих провайдеров токена
/// (`FirebasePushTokenProvider.create`, `RuStorePushTokenProvider.create`).
/// Host-app сам ничего вызывать не обязан; вызвать [ensureCreated]
/// повторно — способ обновить видимые подписи (например, при смене языка).
abstract final class NsgNotificationChannels {
  /// Тревоги — уровень срочности `timeSensitive` / `critical` у продукта.
  /// Важность `IMPORTANCE_HIGH`: всплытие поверх экрана и звук.
  static const String alarms = 'nsg_alarms';

  /// Рядовые уведомления продукта — уровень `active`: статусы объектов,
  /// события, информация. Обычная важность.
  static const String general = 'nsg_general';

  /// Набор закрыт и общий с сервером (см. docstring библиотеки).
  ///
  /// Чат- и звонковых каналов здесь нет и быть не должно: их пуши ключа не
  /// несут вовсе, ими распоряжается канал приложения по умолчанию, и
  /// поведение существующих установок этой задачей не меняется.
  static const Set<String> known = <String>{alarms, general};

  /// Подписи по умолчанию — они видны человеку в системных настройках
  /// приложения, поэтому написаны для него, а не для нас.
  static const String defaultAlarmsName = 'Тревоги';

  /// Описание канала тревог (под именем в системных настройках).
  static const String defaultAlarmsDescription =
      'Срочные уведомления: всплывают поверх экрана и звучат.';

  /// Имя канала рядовых уведомлений.
  static const String defaultGeneralName = 'Уведомления';

  /// Описание канала рядовых уведомлений.
  static const String defaultGeneralDescription = 'Статусы объектов и события.';

  /// Описание канала тревог — данными, без обращения к платформе (то, что
  /// можно проверить тестом).
  static AndroidNotificationChannel alarmsChannel({
    String name = defaultAlarmsName,
    String description = defaultAlarmsDescription,
  }) => AndroidNotificationChannel(
    alarms,
    name,
    description: description,
    // Ровно то, ради чего канал и заводится: IMPORTANCE_HIGH — всплытие
    // поверх экрана и звук. Ниже — тревога станет обычной строкой в
    // шторке; `Importance.max` Android не рекомендует сам.
    importance: Importance.high,
    playSound: true,
    enableVibration: true,
  );

  /// Описание канала рядовых уведомлений.
  static AndroidNotificationChannel generalChannel({
    String name = defaultGeneralName,
    String description = defaultGeneralDescription,
  }) => AndroidNotificationChannel(
    general,
    name,
    description: description,
    // Обычная важность: звук есть, всплытия нет. Статусы объектов не
    // должны перекрывать экран — иначе человек выключит категорию, и
    // вместе с ней потеряется смысл разделения на два канала.
    importance: Importance.defaultImportance,
  );

  /// Завести оба канала на устройстве. Идемпотентно.
  ///
  /// Вне Android — no-op: каналов там нет как понятия, а дёргать плагин
  /// незачем.
  ///
  /// Неудача не роняет инициализацию пушей: канал нужен для того, КАК
  /// показать уведомление, а регистрация токена определяет, придёт ли оно
  /// вообще. Уронив второе из-за первого, мы обменяли бы тихую тревогу на
  /// отсутствующую.
  ///
  /// **Проверять — на устройстве.** Успешный возврат означает лишь, что
  /// платформа приняла вызов. Настоящее свидетельство — категории
  /// «Тревоги» и «Уведомления» в системных настройках приложения
  /// (`adb shell dumpsys notification_manager | grep nsg_`).
  static Future<void> ensureCreated({
    String alarmsName = defaultAlarmsName,
    String alarmsDescription = defaultAlarmsDescription,
    String generalName = defaultGeneralName,
    String generalDescription = defaultGeneralDescription,
  }) async {
    final android = _androidPlugin;
    if (android == null) return;
    try {
      await android.createNotificationChannel(
        alarmsChannel(name: alarmsName, description: alarmsDescription),
      );
      await android.createNotificationChannel(
        generalChannel(name: generalName, description: generalDescription),
      );
    } catch (e, st) {
      // Своего канала для ошибок у SDK нет, а тревоги ещё никто не шлёт:
      // единственный потребитель этой строки сейчас — тот, кто проходит
      // §6.7 ТЗ с подключённым устройством.
      if (kDebugMode) {
        debugPrint(
          '[NsgNotificationChannels] createNotificationChannel: $e\n$st',
        );
      }
    }
  }

  /// Удалить оба канала — **инструмент отрицательного свидетельства**
  /// (§6.8 ТЗ), не продакшн-путь.
  ///
  /// Проверка звучит так: убрать канал тревог → тревога обязана прийти
  /// тихо и без всплытия. Не изменилось — значит канал ничего не нёс, и
  /// этап 3 сделан вхолостую.
  ///
  /// **Почему без этого метода свидетельство недостоверно.** Каналы живут
  /// в системе, а не в приложении: они переживают перезапуск и обновление
  /// и исчезают только с удалением приложения или очисткой его данных.
  /// Убрать вызов [ensureCreated] из кода и переустановить сборку —
  /// недостаточно, канал останется с прошлого запуска, тревога всё так же
  /// всплывёт, и проверяющий сделает вывод, обратный правильному.
  ///
  /// Порядок: вызвать этот метод (например, из отладочной кнопки), НЕ
  /// перезапуская приложение — иначе [ensureCreated] на старте заведёт
  /// каналы обратно, — и отправить тревогу.
  ///
  /// **След остаётся.** Система помнит удалённые каналы: созданный заново
  /// канал восстановит прежние пользовательские настройки, а не наши
  /// умолчания. Для проверки это неважно, для «починить испорченный
  /// канал» — важно, и так это не работает.
  static Future<void> deleteAll() async {
    final android = _androidPlugin;
    if (android == null) return;
    for (final id in known) {
      await android.deleteNotificationChannel(channelId: id);
    }
  }

  /// Android-реализация плагина, либо `null` на прочих платформах.
  ///
  /// Проверка через `dart:io`, а не через `defaultTargetPlatform`: в
  /// тестах последний по умолчанию отвечает «android» и мы бы полезли в
  /// method channel, которого под тестом нет.
  static AndroidFlutterLocalNotificationsPlugin? get _androidPlugin {
    if (kIsWeb || !Platform.isAndroid) return null;
    return FlutterLocalNotificationsPlugin()
        .resolvePlatformSpecificImplementation<
          AndroidFlutterLocalNotificationsPlugin
        >();
  }
}

/// Запросить POST_NOTIFICATIONS (Android 13+). Возвращает, разрешены ли
/// уведомления.
///
/// До Android 13 разрешение выдавалось при установке — там плагин просто
/// сообщает текущее состояние (`areNotificationsEnabled`), диалога нет.
/// Вне Android вызов бессмыслен, отвечаем `true`: «ничего не мешает».
///
/// **Зачем отдельно от каналов.** Канал определяет, КАК показать
/// уведомление; разрешение — покажут ли его вообще. Без POST_NOTIFICATIONS
/// на Android 13+ не придёт ничего, и самый громкий канал этого не
/// перебьёт.
///
/// **Кто это зовёт.** Только RuStore-путь. На FCM-пути разрешение уже
/// запрашивает `FirebaseMessaging.requestPermission()` — проверено по коду
/// плагина: на API 33+ он просит ровно этот POST_NOTIFICATIONS. Позвать
/// здесь второй раз значило бы показать человеку два системных диалога
/// подряд.
Future<bool> requestAndroidNotificationsPermission() async {
  if (kIsWeb || !Platform.isAndroid) return true;
  try {
    final android = FlutterLocalNotificationsPlugin()
        .resolvePlatformSpecificImplementation<
          AndroidFlutterLocalNotificationsPlugin
        >();
    // `null` от плагина — «не знаем»; считаем разрешённым, чтобы не
    // советовать «включите уведомления» тому, у кого они включены.
    return await android?.requestNotificationsPermission() ?? true;
  } catch (e) {
    // Плагин отказывает, если системный диалог разрешений уже открыт
    // (host-app просит своё). Это не отказ пользователя — вердикт вынесет
    // тот, другой запрос.
    if (kDebugMode) {
      debugPrint(
        '[NsgNotificationChannels] requestNotificationsPermission: $e',
      );
    }
    return true;
  }
}
