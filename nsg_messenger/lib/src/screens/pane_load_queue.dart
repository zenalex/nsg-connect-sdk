/// **Очередь стартовой загрузки скрытых панелей** — issue #141.
///
/// **Откуда взялось.** Замер на проде 14.08.2026: восемь вызовов от ОДНОГО
/// человека в одну секунду, каждый по ~2,2 с. Причём `listChatFolders` с
/// двумя запросами занял 1,48 с, а `listRooms` с пятнадцатью — 2,21 с. То
/// есть длительность определялась не работой вызова, а тем, что все они
/// пришли разом: сервер однопоточный, и каждый вызов отчитывался о полном
/// времени очереди.
///
/// **Почему их приходит восемь.** Рабочая область держит панели комнат в
/// дереве постоянно (скрытые — `Offstage`), и это правильно: так переживают
/// скрытие прокрутка, черновик и уже загруженная история. Но раз панель в
/// дереве — у неё отработал `initState`, а там стартовая загрузка: история,
/// карточка комнаты, команды ботов, сводка задач. Сколько комнат открыто,
/// столько наборов и уходит одновременно, включая невидимые.
///
/// **Что делает эта очередь.** Активная панель грузится сразу и ни за кем не
/// ждёт. Скрытые встают в очередь и грузятся по одной. Суммарно работы
/// столько же, но человек ждёт только свою панель, а не чужие.
///
/// **Почему не «грузить скрытые только при показе».** Это отняло бы то,
/// ради чего конструкцию и делали: первое переключение на панель стало бы
/// заметным. Здесь оно остаётся мгновенным — к моменту переключения панель
/// обычно уже догрузилась.
///
/// **А если не догрузилась** — переключение [promote] запускает её немедленно,
/// не дожидаясь очереди: человек уже смотрит на эту панель, и держать его за
/// чужой загрузкой незачем.
library;

import 'dart:async';

import 'package:meta/meta.dart';

/// Стартовая загрузка одной панели. Возвращает future, который очередь ждёт
/// перед тем, как взяться за следующую.
typedef PaneLoad = Future<void> Function();

abstract final class PaneLoadQueue {
  /// Ожидающие своей очереди, в порядке постановки (Map в Dart хранит
  /// порядок вставки — отдельный список был бы вторым источником правды).
  static final Map<Object, PaneLoad> _pending = <Object, PaneLoad>{};

  /// Ключи, чья загрузка уже началась. Нужны, чтобы [promote] не запустил
  /// работу второй раз: панель, ставшая активной во время своей же загрузки,
  /// иначе загрузилась бы дважды.
  static final Set<Object> _started = <Object>{};

  static bool _draining = false;

  @visibleForTesting
  static int get pendingCount => _pending.length;

  @visibleForTesting
  static void resetForTesting() {
    _pending.clear();
    _started.clear();
    _draining = false;
  }

  /// Поставить загрузку скрытой панели в очередь. Повторная постановка того
  /// же ключа игнорируется: панель пересоздаётся при перестройке дерева, и
  /// без этого одна комната набивала бы очередь собой.
  static void enqueue(Object key, PaneLoad load) {
    if (_started.contains(key) || _pending.containsKey(key)) return;
    _pending[key] = load;
    unawaited(_drain());
  }

  /// Загрузить немедленно, минуя очередь, — панель показали человеку.
  ///
  /// Если загрузка уже началась или прошла, не делает ничего: повторный
  /// запуск стоил бы второй порции запросов ровно там, где мы их и
  /// экономим.
  static void promote(Object key) {
    final load = _pending.remove(key);
    if (load == null) return;
    _started.add(key);
    unawaited(_run(load));
  }

  /// Панель ушла из дерева — снимаем её из очереди, если ещё не начали.
  /// Иначе очередь держала бы работу для того, кого уже нет.
  static void cancel(Object key) {
    _pending.remove(key);
    _started.remove(key);
  }

  static Future<void> _drain() async {
    if (_draining) return;
    _draining = true;
    try {
      while (_pending.isNotEmpty) {
        final key = _pending.keys.first;
        final load = _pending.remove(key)!;
        _started.add(key);
        await _run(load);
      }
    } finally {
      _draining = false;
    }
  }

  /// Одна загрузка. Ошибка НЕ должна останавливать очередь: упавшая панель —
  /// это одна непоказанная история, а вставшая очередь — все остальные.
  static Future<void> _run(PaneLoad load) async {
    try {
      await load();
    } catch (_) {
      // Диагностика — забота самой загрузки; здесь важно только продолжить.
    }
  }
}
