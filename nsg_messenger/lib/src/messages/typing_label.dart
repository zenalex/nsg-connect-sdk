import '../i18n/generated/nsg_l10n.dart';

/// Надпись индикатора «кто сейчас готовит сообщение» — общая точка решения
/// для ВСЕХ поверхностей (footer открытого чата, строка списка чатов,
/// строка внутри папки).
///
/// Почему одна функция, а не по копии на экран: поверхностей три, и
/// расхождение между ними читается пользователем как разное поведение
/// продукта («в списке пишет одно, в чате другое — что-то сломалось»).
///
/// **Зачем вообще разные глаголы.** Бот-агент думает МИНУТАМИ (жёсткий
/// таймаут — полчаса) и всё это время честно шлёт Matrix `m.typing`
/// heartbeat-ом. Индикатор при этом работает правильно, врёт СЛОВО:
/// человек не печатает десять минут, поэтому «печатает…» читается как
/// зависание бота. Меняем глагол, механику не трогаем.
///
/// * [count] — сколько всего сейчас печатает;
/// * [botCount] — сколько из них не люди (боты / интеграции / ИИ-агенты).
///   `0`, если сервер старый и признака не прислал, — тогда формулировка
///   ровно прежняя;
/// * [names] — отображаемые имена, если они известны вызывающему. Список
///   может быть короче [count]: чатлист при двух и более печатающих имён
///   не резолвит (в строку всё равно не влезут).
///
/// Правила:
///   * один печатающий — «{имя} печатает…» / «{имя} анализирует…»;
///   * двое-и-больше людей — как было («X и Y печатают…» / «N печатают…»);
///   * двое-и-больше, среди них хоть один бот — НЕЙТРАЛЬНЫЙ глагол
///     («N участников готовят ответ…»). Здесь важно не соврать: сказать
///     «печатают» — соврать про бота (ровно тот баг, из-за которого всё
///     затевалось), сказать «анализируют» — соврать про человека, а
///     перечислять по-разному каждого («Маша печатает, бот анализирует»)
///     не влезет в строку списка чатов. Общий глагол верен для обоих:
///     и человек, и агент действительно готовят ответ.
String typingIndicatorLabel(
  NsgL10n l10n, {
  required int count,
  required int botCount,
  List<String> names = const <String>[],
}) {
  if (count <= 0) return '';
  if (count == 1 && names.isNotEmpty) {
    return botCount > 0
        ? l10n.typingSingleBot(names.first)
        : l10n.typingSingle(names.first);
  }
  // Ботов не перечисляем поимённо (см. выше) — счётная формулировка.
  if (botCount > 0) return l10n.typingManyMixed(count);
  if (count == 2 && names.length >= 2) {
    return l10n.typingPair(names[0], names[1]);
  }
  return l10n.typingManyCount(count);
}
