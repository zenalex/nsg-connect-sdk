/// **Issue #86**: почему устройство НЕ получает пуш-уведомления.
///
/// Отсутствие пуш-токена — это СОСТОЯНИЕ, а не пустота. До issue #86
/// провайдер, не сумевший получить токен, просто молчал: единственным
/// следом был `debugPrint` под `kDebugMode`, которого в релизной сборке
/// нет вообще. Владелец две недели не получал уведомлений и не мог
/// понять почему, а сервер всё это время рапортовал `sent` в мёртвую
/// регистрацию двухнедельной давности. Состояние выведено наружу
/// именно затем, чтобы такой отказ было ВИДНО — в приложении, а не в
/// отладочной консоли, которой у пользователя нет.
///
/// Причины разделены намеренно: они лечатся РАЗНЫМ, и подсказка не по
/// адресу хуже молчания.
///   * [permissionDenied] — лечится выдачей разрешения (системные
///     настройки приложения);
///   * [tokenUnavailable] — разрешение есть, а токена нет: сеть (Wi-Fi
///     блокирует порт 5223 к `push.apple.com`) либо отсутствие push-
///     entitlement в сборке. Кнопка «разрешить уведомления» здесь
///     бесполезна — разрешение уже выдано.
enum PushTokenStatus {
  /// Вердикта ещё нет: идёт запрос разрешения / ожидание APNs-токена.
  /// UI обязан молчать — показывать «сломано» на первых секундах старта
  /// значит пугать людей, у которых всё в порядке.
  pending,

  /// Токен получен — уведомления доедут.
  ready,

  /// ОС не разрешила приложению показывать уведомления.
  permissionDenied,

  /// Разрешение выдано, но платформа так и не выдала токен.
  tokenUnavailable,

  /// Пуши на этой платформе не поддерживаются (desktop / web) либо
  /// host-app не передал провайдера (embed-режим без пушей). Чинить
  /// нечего — UI молчит.
  unsupported,
}

extension PushTokenStatusX on PushTokenStatus {
  /// Уведомления заведомо не придут, И человеку есть что с этим делать.
  ///
  /// [PushTokenStatus.pending] и [PushTokenStatus.unsupported] сюда НЕ
  /// входят: в первом случае вердикта ещё нет, во втором чинить нечего —
  /// в обоих сообщать не о чем.
  bool get isBroken =>
      this == PushTokenStatus.permissionDenied ||
      this == PushTokenStatus.tokenUnavailable;
}
