/// **TASK64**: список языков, доступных для заполнения профиля.
///
/// Живёт в SDK, а не на сервере намеренно (TASK64.md §2): сервер
/// валидирует ФОРМАТ кода (короткий BCP-47), а не членство в списке —
/// иначе каждый новый язык требовал бы деплоя сервера, а «или даже
/// просто по выбору пользователя» (постановщик) стало бы невозможным.
/// Клиент же показывает конечный набор, чтобы не превращать выбор в
/// свободный ввод кода.
library;

/// Код языка → самоназвание (его показываем в пикере: человек ищет
/// «Deutsch», а не «немецкий»). Порядок — по ожидаемой частоте у нашей
/// аудитории, он же порядок в диалоге «Добавить язык».
const Map<String, String> kProfileLocaleNames = <String, String>{
  'ru': 'Русский',
  'en': 'English',
  'de': 'Deutsch',
  'fr': 'Français',
  'es': 'Español',
  'it': 'Italiano',
  'pt': 'Português',
  'tr': 'Türkçe',
  'uk': 'Українська',
  'kk': 'Қазақша',
  'zh': '中文',
  'ar': 'العربية',
};

/// Подпись языка для пикера: «Deutsch (DE)» — самоназвание плюс код,
/// потому что чипы подписаны кодом и человек должен связать одно с
/// другим. Незнакомый код (профиль заполнен из другого клиента) не
/// прячем — показываем как есть.
String profileLocaleLabel(String code) {
  final name = kProfileLocaleNames[code];
  final upper = code.toUpperCase();
  return name == null ? upper : '$name ($upper)';
}
