import 'package:flutter/foundation.dart';

/// **Комната, которую человек видит прямо сейчас.**
///
/// Нужна тем, кто решает «показывать ли уведомление»: сообщение в
/// открытом чате приходит прямо на глазах, и плашка поверх него — шум.
///
/// Заявку делает `ChatScreen` из той же точки, что и presence
/// (`_firePresence`), поэтому здесь отражены все случаи разом: открытие
/// чата, переключение вкладки рабочего набора, перекрытие маршрутом,
/// возврат из фона, закрытие экрана. Дублировать эту логику отдельным
/// набором вызовов значило бы гарантированно разойтись с ней.
///
/// Статический слот, а не InheritedWidget: спрашивающие живут ВНЕ дерева
/// (обработчик событий шины), а видимый чат в приложении ровно один —
/// на десктопной раскладке им владеет активная панель.
class ActiveRoom {
  ActiveRoom._();

  static final ValueNotifier<int?> _current = ValueNotifier<int?>(null);

  /// Для виджетов, которым нужно перестраиваться на смену.
  static ValueListenable<int?> get listenable => _current;

  /// Id открытой комнаты; `null` — человек не в чате.
  static int? get current => _current.value;

  /// Чат стал видимым.
  static void claim(int roomId) => _current.value = roomId;

  /// Чат перестал быть видимым.
  ///
  /// Снимаем, только если заявка НАША: на десктопе экранов несколько, и
  /// уходящий в фон не должен стирать заявку того, кто только что стал
  /// активным (порядок колбэков между панелями не гарантирован).
  static void release(int roomId) {
    if (_current.value == roomId) _current.value = null;
  }

  @visibleForTesting
  static void reset() => _current.value = null;
}
