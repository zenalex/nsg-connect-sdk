/// **Отчёт о пропаже связи** — то, что уезжает в трекер, когда стрим
/// событий не вернулся за отведённое время (issue #118).
///
/// Отдельный тип, а не `StateError` с готовым текстом, ради одной вещи:
/// **числа не должны стоять в тексте**. Трекер группирует события по
/// сообщению, поэтому «не восстановилась за 137 с» и «за 1240 с» — это две
/// разные группы. К разбору 27.08.2026 таких групп в проекте накопилось
/// 109 из 275: одна беда занимала сорок процентов списка и выдавливала из
/// него всё остальное (issue #170).
///
/// Текст теперь стабилен, а числа едут тегами — по ним и ищут.
library;

/// Пропажа связи со стримом событий, о которой сообщили в трекер.
class StreamOutage implements Exception {
  const StreamOutage({
    required this.lasted,
    required this.attempts,
    required this.cause,
  });

  /// Сколько связи не было к моменту отчёта.
  final Duration lasted;

  /// Сколько попыток переподключения к этому моменту не удались.
  final int attempts;

  /// Что сказал транспорт — уже прочищенный `describeTransportError`.
  final String cause;

  /// Теги события. Ключи через точку — как у остальных наших
  /// (`chat.action`, `http.status`).
  Map<String, String> get tags => {
    'outage.seconds': '${lasted.inSeconds}',
    'outage.attempts': '$attempts',
  };

  /// **Без чисел** — см. разбор в шапке файла.
  @override
  String toString() => 'Связь со стримом не восстановилась: $cause';
}
