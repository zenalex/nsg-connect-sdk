/// **Подложки подсветки в сообщениях**: код, цитата, найденное поиском,
/// упоминания.
///
/// Жалоба: «на мобильных в зоне подсветки плохо читается текст», просьба —
/// «уменьшить прозрачность плашек». Прозрачность действительно виновата,
/// но лечится не тем, чем кажется.
///
/// Все подложки строились от цвета ТЕКСТА: `textColor.withValues(alpha: …)`
/// поверх пузыря. То есть плашка тянет фон К ЦВЕТУ ТЕКСТА, и чем менее
/// прозрачной её делать, тем МЕНЬШЕ остаётся контраста — в тёмной теме
/// светлая плашка под светлым текстом сливается тем сильнее, чем она
/// плотнее. Поэтому здесь подложка строится в сторону контраста: тёмная
/// тема — затемняем фон пузыря, светлая — тоже затемняем, но слабее. Текст
/// при этом остаётся полной насыщенности.
///
/// Вторая половина проблемы — притушенный текст. Цитата рисовалась
/// `textColor.withValues(alpha: 0.6…0.7)` НА плашке: два ослабления
/// накладывались друг на друга. Тексту на подложке место в [onHighlight].
library;

import 'dart:math' as math;

import 'package:flutter/material.dart';

/// Непрозрачная подложка для плашки внутри пузыря сообщения.
///
/// Возвращает именно непрозрачный цвет, а не полупрозрачный: плашка
/// накладывается на разные фоны (свой пузырь, чужой, выделенная строка), и
/// «прозрачный поверх неизвестного» — это и есть источник непредсказуемого
/// контраста.
///
/// [strength] — насколько плашка отличается от фона: `subtle` для цитаты
/// (крупный блок, не должен спорить с текстом), `strong` для кода и
/// найденного (мелкие фрагменты, их надо выделить).
Color highlightSurface(
  Color bubbleColor,
  Brightness brightness, {
  HighlightStrength strength = HighlightStrength.strong,
}) {
  final dark = brightness == Brightness.dark;
  // В тёмной теме затемняем сильнее: там фон пузыря и так близок к
  // чёрному, и слабое затемнение просто не видно.
  final amount = switch ((dark, strength)) {
    (true, HighlightStrength.strong) => 0.32,
    (true, HighlightStrength.subtle) => 0.18,
    (false, HighlightStrength.strong) => 0.10,
    (false, HighlightStrength.subtle) => 0.06,
  };
  return Color.alphaBlend(Colors.black.withValues(alpha: amount), bubbleColor);
}

enum HighlightStrength { subtle, strong }

/// Цвет текста НА подложке.
///
/// Раньше текст на плашках дополнительно приглушался (0.6–0.7) — вместе с
/// самой плашкой это давало двойное ослабление. Здесь текст остаётся
/// насыщенным; для вторичных строк (автор цитаты, время) достаточно
/// [secondary], который ослаблен заметно меньше прежнего.
Color onHighlight(Color textColor, {bool secondary = false}) =>
    secondary ? textColor.withValues(alpha: 0.85) : textColor;

/// Цвет, который ТОЧНО читается на [background].
///
/// Упоминания и найденное поиском красились акцентом (`primary`), а он на
/// своём пузыре (`primaryContainer`) оказывается почти тем же цветом — на
/// мобильном это и читалось хуже всего. Если акцент не добирает до порога,
/// откатываемся на основной цвет текста и отличаем фрагмент насыщенностью,
/// а не цветом: нечитаемый акцент хуже отсутствия акцента.
Color ensureReadable(
  Color accent,
  Color background, {
  required Color fallback,
  double minRatio = 4.5,
}) => contrastRatio(accent, background) >= minRatio ? accent : fallback;

/// **Акцент, который читается, НЕ переставая быть акцентом.**
///
/// Жалоба: «с белым текстом всё ок, читается везде, а вот с оранжевым —
/// проблема. Получается оранжевый на оранжевом в углах».
///
/// Причина в том, что в glass-темах акцент — ЭТО цвет обоев: у sunset
/// `primary` буквально равен нижнему пятну подложки (`#E89A55`), у ember
/// — тоже (`#E0682E`). А свой пузырь — тот же акцент под 33%. Ссылка,
/// упоминание, имя автора, шапка цитаты красились чистым `primary` и
/// сливались с тем, на чём лежат.
///
/// [ensureReadable] тут не спасает: он отвечает «да/нет» и на «нет»
/// отдаёт основной цвет текста — ссылка становится неотличима от обычного
/// текста. Здесь ОТТЕНОК сохраняем, а светлоту двигаем: подмешиваем цвет
/// текста ([toward]) ровно настолько, чтобы взять порог. Оранжевый
/// остаётся оранжевым, только светлее фона — «акцент» читается и как
/// смысл, и глазами.
///
/// Порог меряем по тому, что видно на экране: полупрозрачный цвет сначала
/// накладываем на фон (у glass-тем текст — белый под альфой 0.96).
Color readableAccent(
  Color accent,
  Color background, {
  required Color toward,
  double minRatio = 4.5,
}) {
  double ratioOn(Color c) =>
      contrastRatio(Color.alphaBlend(c, background), background);
  if (ratioOn(accent) >= minRatio) return accent;
  for (var i = 1; i <= _accentMixSteps; i++) {
    final mixed = Color.lerp(accent, toward, i / _accentMixSteps)!;
    if (ratioOn(mixed) >= minRatio) return mixed;
  }
  // Даже полностью подмешанный не взял порог — фон непригоден в принципе
  // (так бывает на светлом пятне обоев). Отдаём цвет текста: он хотя бы
  // не хуже соседних строк.
  return toward;
}

/// Шаг подмешивания — 5%. Мельче не имеет смысла: разницу в 1/20
/// светлоты глаз уже не отличает, а перебор дешевле любой аналитики по
/// обратной формуле WCAG (та не учла бы альфу и нелинейность канала).
const int _accentMixSteps = 20;

/// Непрозрачный вариант [surface] для плашек, лежащих на обоях.
///
/// В glass-темах `surface` вообще прозрачный, а `surfaceContainer*` —
/// белый под альфой: «плашка» на них не фон, а фильтр поверх обоев, и
/// контраст с ней зависит от того, какое пятно оказалось снизу. [ink] —
/// опорный тёмный тон палитры (`NsgMessageBubbleTokens.bubbleInk`);
/// у обычных, непрозрачных тем он `null` и всё остаётся как было.
Color inkedSurface(Color surface, Color? ink) =>
    ink == null ? surface : Color.alphaBlend(surface, ink);

/// **Тени для текста, лежащего ПРЯМО НА ОБОЯХ** (плашка даты, подписи
/// поверх стекла).
///
/// Предложение Энди — «шрифт с небольшой тенью увеличит читаемость» — верно
/// именно здесь. В пузыре тень не нужна и вредна: там фон непрозрачный и
/// контраст уже гарантирован, а размытый ореол на мелком кегле лишь мылит
/// буквы. А вот над обоями фон заранее неизвестен — тень даёт тёмный
/// ореол независимо от того, какое пятно оказалось снизу.
///
/// Две тени, а не одна: плотная короткая держит края глифа, мягкая
/// широкая гасит светлый фон вокруг.
const List<Shadow> kOnWallpaperTextShadows = [
  Shadow(color: Color(0xB3000000), blurRadius: 2),
  Shadow(color: Color(0x80000000), blurRadius: 6, offset: Offset(0, 1)),
];

/// Контраст двух цветов по WCAG (1..21). Оба должны быть непрозрачными —
/// полупрозрачный сначала наложите на фон (`Color.alphaBlend`).
///
/// Нужен тестам: «читается ли» — проверяемое утверждение, а не мнение.
double contrastRatio(Color a, Color b) {
  final la = _relativeLuminance(a);
  final lb = _relativeLuminance(b);
  final lighter = la > lb ? la : lb;
  final darker = la > lb ? lb : la;
  return (lighter + 0.05) / (darker + 0.05);
}

double _relativeLuminance(Color c) {
  double channel(double v) =>
      v <= 0.03928 ? v / 12.92 : math.pow((v + 0.055) / 1.055, 2.4).toDouble();
  return 0.2126 * channel(c.r) + 0.7152 * channel(c.g) + 0.0722 * channel(c.b);
}
