/// **issue #56**: одна строка превью — списка чатов и уведомления —
/// рисовать разметку не умеет, и человек видел сырые звёздочки с
/// backtick-ами. Особенно заметно на ответах ботов: они отвечают
/// markdown-ом по своей природе.
///
/// Правило простое: знаки снимаем, СОДЕРЖИМОЕ оставляем — превью должно
/// говорить, о чём сообщение.
///
/// **Тот же набор случаев продублирован на сервере**
/// (`test/unit/markdown_plain_test.dart`): сервер и SDK — отдельные
/// пакеты без общей зависимости, чистка у каждого своя, и расхождение
/// должны поймать тесты, а не пользователь.
library;

import 'package:flutter_test/flutter_test.dart';
import 'package:nsg_messenger/src/messages/markdown_plain.dart';

void main() {
  test('жирный, курсив, зачёркнутый — только содержимое', () {
    expect(
      stripMarkdown('**важно** и *курсив* и ~~не так~~'),
      'важно и курсив и не так',
    );
  });

  test('инлайн-код теряет backtick-и', () {
    expect(
      stripMarkdown('запусти `flutter test` сейчас'),
      'запусти flutter test сейчас',
    );
  });

  test('ссылка сводится к подписи', () {
    // URL занял бы всю строку превью и ничего бы не сообщил.
    expect(
      stripMarkdown('см. [документацию](https://example.com/very/long/path)'),
      'см. документацию',
    );
  });

  test('голый URL остаётся — он и есть весь текст', () {
    expect(stripMarkdown('https://example.com/a'), 'https://example.com/a');
  });

  test('от блока кода остаётся первая непустая строка', () {
    expect(
      stripMarkdown('вот:\n```dart\n\nvoid main() {}\nprint(1);\n```'),
      'вот: void main() {}',
    );
  });

  test('незакрытый блок кода тоже разбирается', () {
    expect(stripMarkdown('гляди:\n```\nls -la'), 'гляди: ls -la');
  });

  test('маркеры списка снимаются, текст пунктов склеивается', () {
    expect(stripMarkdown('- один\n- два\n3. три'), 'один два три');
  });

  test('полоска цитаты снимается', () {
    expect(stripMarkdown('> цитата\nответ'), 'цитата ответ');
  });

  test('перевод строки становится пробелом', () {
    expect(stripMarkdown('первая\nвторая'), 'первая вторая');
  });

  test('пустые строки не оставляют дыр', () {
    expect(stripMarkdown('раз\n\n\nдва'), 'раз два');
  });

  test('обычный текст не меняется', () {
    expect(stripMarkdown('просто сообщение'), 'просто сообщение');
  });

  test('пустая строка остаётся пустой', () {
    expect(stripMarkdown(''), '');
  });

  test('умножение не превращается в курсив', () {
    // Тот же анти-ложный-срабатыватель, что в рендере: `2*3` — не разметка.
    expect(stripMarkdown('2*3=6'), '2*3=6');
  });

  test('подчёркивания в имени файла сохраняются', () {
    expect(
      stripMarkdown('файл my_long_name.dart готов'),
      'файл my_long_name.dart готов',
    );
  });
}
